const labelKey={chest:'chest',waist:'waist',hips:'hip'};
const mean=a=>a.reduce((s,v)=>s+v,0)/a.length;
const round=n=>Math.round(n*1000)/1000;

async function* rows(split) {
  const stream=fs.createReadStream(path.join(dir,split+'.ndjson.gz')).pipe(createGunzip());
  for await(const line of createInterface({input:stream,crlfDelay:Infinity})) yield JSON.parse(line);
}
function observation(r) {
  if (!r.front?.rows.length || !r.side?.rows.length || !r.metadata) throw new Error('缺少配对观测或元数据');
  const input={tier:'photos',heightCm:r.metadata.height_cm,weightKg:r.metadata.weight_kg};
  const obs={front:observeView(r.front),side:observeView(r.side)};
  if(!Object.keys(obs.front.samples).length || !Object.keys(obs.side.samples).length) throw new Error('缺少可见躯干');
  return {input,obs};
}
function labels(split) {return JSON.parse(fs.readFileSync(path.join(dir,split+'-measurements.json')));}
function truth(table,id) {
  const y=girthNames.map(k=>table[id]?.[labelKey[k]]);
  if(y.some(v=>!Number.isFinite(v)||v<=0)) throw new Error('缺少量体标签');
  return y;
}
const predict=(w,x)=>w.reduce((s,v,i)=>s+v*x[i],0);

// Subject-balanced ridge; one factorization solves for the three output girths.
function regress(data,lambda) {
  const n=data[0].x.length, counts=new Map();
  for(const {id} of data) counts.set(id,(counts.get(id)??0)+1);
  const a=Array.from({length:n},()=>new Float64Array(n+3));
  for(const {id,x,y} of data) {
    const weight=1/counts.get(id);
    for(let i=0;i<n;i++) {
      for(let j=0;j<n;j++) a[i][j]+=weight*x[i]*x[j];
      for(let j=0;j<3;j++) a[i][n+j]+=weight*x[i]*y[j];
    }
  }
  for(let i=1;i<n;i++) a[i][i]+=lambda;
  for(let i=0;i<n;i++) {
    let p=i;
    for(let j=i+1;j<n;j++) if(Math.abs(a[j][i])>Math.abs(a[p][i])) p=j;
    [a[i],a[p]]=[a[p],a[i]];
    const diag=a[i][i];
    for(let k=i;k<n+3;k++) a[i][k]/=diag;
    for(let j=0;j<n;j++) if(j!==i) {
      const factor=a[j][i];
      for(let k=i;k<n+3;k++) a[j][k]-=factor*a[i][k];
    }
  }
  return Object.fromEntries(girthNames.map((name,j)=>[name,a.map(row=>row[n+j])]));
}
function validationScore(set,w) {
  const byPerson=new Map();
  for(const {x,y,id} of set) {
    if(!byPerson.has(id)) byPerson.set(id,[]);
    byPerson.get(id).push(mean(girthNames.map((k,i)=>Math.abs(predict(w[k],x)-y[i]))));
  }
  return mean([...byPerson.values()].map(mean));
}

async function train() {
  const data=[],table=labels('train');
  for await(const r of rows('train')) {
    if(r.status==='failed') continue;
    const {input,obs}=observation(r);
    data.push({id:r.subject_id,x:geometryFeatures(input,obs),y:truth(table,r.subject_id)});
  }
  const validation=d=>createHash('sha256').update(d.id).digest()[0]%5===0;
  const train=data.filter(d=>!validation(d)),valid=data.filter(validation);
  const scores=[.05,.5,5].map(lambda=>({lambda,mae:validationScore(valid,regress(train,lambda))}));
  const best=scores.reduce((a,b)=>a.mae<b.mae?a:b);
  const weights=regress(data,best.lambda);
  fs.writeFileSync(weightsFile,'// Generated by npm run bodym:train, using only the train partition.\nexport const geometryWeights = '+JSON.stringify(weights,null,2)+';\n');
  save('training.json',{split:'train',group:'SHA256(subject_id)[0] modulo 5',fitSubjects:new Set(train.map(r=>r.id)).size,
    validationSubjects:new Set(valid.map(r=>r.id)).size,scores,selectedLambda:best.lambda,refitPairs:data.length});
  console.log('Weights frozen from train:',data.length,'pairs',scores);
}

function metrics(entries,k) {
  if(!entries.length) return null;
  const idx=girthNames.indexOf(k),errors=entries.map(r=>r.errors[idx]).sort((a,b)=>a-b),people=new Map();
  for(const r of entries) {
    if(!people.has(r.subject)) people.set(r.subject,[]);
    people.get(r.subject).push(r.errors[idx]);
  }
  return {mae:round(mean(errors)),p90:round(errors[Math.ceil(.9*errors.length)-1]),subjectMAE:round(mean([...people.values()].map(mean)))};
}
async function evaluate(split) {
  const table=labels(split),methods=['quick','previous','current'];
  const entries=Object.fromEntries(methods.map(k=>[k,[]]));
  const coverage=Object.fromEntries(methods.map(k=>[k,{success:0,partial:0,failed:0}]));
  const failures=[]; let total=0;
  for await(const r of rows(split)) {
    total++;
    let common;
    try { common=observation(r); } catch(e) { if(failures.length<5) failures.push([r.photo_id,e.message]); }
    for(const method of methods) {
      try {
        let p;
        if(method==='quick') p=fitBody({tier:'quick',heightCm:r.metadata.height_cm,weightKg:r.metadata.weight_kg});
        else {
          const {input,obs}=common;
          if(method==='current') p=fitGeometry(input,template,obs);
          else {
            const views=Object.fromEntries(['front','side'].map(v=>[v,observedSections(obs[v],template.rest,v)]));
            p=fitBody({...input,views});
          }
        }
        const cm=measureProfile(template,p).cm,y=truth(table,r.subject_id);
        const errors=girthNames.map((k,i)=>Math.abs(cm[k]-y[i]));
        if(!errors.every(Number.isFinite)) throw new Error('无效网格尺寸');
        entries[method].push({subject:r.subject_id,photo:r.photo_id,errors});
        coverage[method][method!=='quick' && r.status==='partial'?'partial':'success']++;
      } catch(e) {coverage[method].failed++; if(failures.length<5) failures.push([r.photo_id,method,e.message]);}
    }
  }
  const ids=methods.map(k=>new Set(entries[k].map(r=>r.photo)));
  const common=entries.current.filter(r=>ids.every(set=>set.has(r.photo)));
  const keep=new Set(common.map(r=>r.photo));
  const results={};
  for(const method of methods) {
    const list=entries[method].filter(r=>keep.has(r.photo));
    results[method]=Object.fromEntries(girthNames.map(k=>[k,metrics(list,k)]));
    const c=coverage[method]; c.coverage=(c.success+c.partial)/total;
  }
  const old=new Map(entries.previous.map(r=>[r.photo,r]));
  const worst=girthNames.map((name,i)=>common.reduce((best,r)=>{
    const delta=r.errors[i]-old.get(r.photo).errors[i];
    return !best || delta>best.delta ? {name,photo:r.photo,delta:round(delta),current:round(r.errors[i]),previous:round(old.get(r.photo).errors[i])}:best;
  },null));
  return {total,common:keep.size,subjects:new Set(common.map(r=>r.subject)).size,coverage,results,worst,failures};
}
